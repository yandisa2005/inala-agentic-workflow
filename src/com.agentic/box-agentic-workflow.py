async def extract_invoice_fields(
    invoice: dict, llm_client: genai.Client, session: ClientSession, tools: list
):
    print(f'--------------Extracting data from invoice "{invoice["name"]}"...')
    prompt = (
        "Extract the following fields from the invoice "
        f"with file_id {invoice['id']}: "
        "client_name, invoice_amount, product_name. "
        "Return the invoice_amount as a float."
    )
    response = await generate(prompt, llm_client, session, tools)

    first_item = response[0] if isinstance(response, list) else response

    # Check for Box API 403 or privilege error responses
    if isinstance(first_item, dict) and "error" in first_item:
        print(f"------------Box API Error ({invoice['name']}): {first_item['error']}")
        return None

    if isinstance(first_item, dict) and "AI_response" in first_item:
        result = json.loads(first_item["AI_response"]["answer"])
    else:
        result = json.loads(first_item) if isinstance(first_item, str) else first_item

    result["file"] = invoice["name"]
    return result

