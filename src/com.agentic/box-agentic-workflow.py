async def get_mcp_tools(session: ClientSession):
    """
    Set up the list of MCP tools that will be used to interact with Box.
    """
    mcp_tools = await session.list_tools()

    for tool in mcp_tools.tools:
        if tool.name in BOX_MCP_TOOLS:
            print(f"----------Selected tool: {tool.name}")

    formatted_tools = []
    for tool in mcp_tools.tools:
        if tool.name in BOX_MCP_TOOLS:
            # Safely retrieve schema whether the SDK uses input_schema or inputSchema
            schema_obj = getattr(tool, "input_schema", getattr(tool, "inputSchema", {}))

            # Safely serialize schema dictionary
            if hasattr(schema_obj, "model_dump"):
                schema_dict = schema_obj.model_dump()
            elif isinstance(schema_obj, dict):
                schema_dict = schema_obj
            else:
                schema_dict = dict(schema_obj)

            formatted_tools.append(
                types.Tool(
                    function_declarations=[
                        {
                            "name": tool.name,
                            "description": tool.description or "",
                            "parameters": schema_dict,
                        }
                    ]
                )
            )

    print(f"----------Formatted Tools count: {len(formatted_tools)}")
    return formatted_tools

def parse_json(content):
    # Try parsing as pure JSON first
    try:
        payload = json.loads(content)
        # print(json.dumps(payload, indent=2, default=str))
        return payload
    except json.JSONDecodeError:
        pass

    # If that fails, try to extract JSON from the text
    # Look for JSON-like content between curly braces
    import re

    json_match = re.search(r"\{.*\}", content, re.DOTALL)
    if json_match:
        try:
            return json.loads(json_match.group())
        except json.JSONDecodeError:
            pass

    # If all else fails, return the original text
    print(f'----------Payload: {content}')
    return content

async def generate(
    prompt: str, llm_client: genai.Client, session: ClientSession = None, tools: list = None
):
    """
    Generate content using the Gemini model using MCP tools if provided.
    """

    def parse_content(content):
        try:
            return parse_json(content.text)
        except json.JSONDecodeError:
            return content.text

    config = (
        types.GenerateContentConfig(temperature=0, tools=tools)
        if session is not None and tools is not None
        else None
    )


    print('-----------Calling LLM Model------------')
    response = llm_client.models.generate_content(
        model=MODEL_NAME,
        contents=prompt,
        config=config,
    )


    if response.candidates[0].content.parts[0].function_call:
        print(
            f'---------[Calling MCP Tool: "{response.candidates[0].content.parts[0].function_call.name}"]'
        )
        function_call = response.candidates[0].content.parts[0].function_call
        response = await session.call_tool(
            function_call.name, arguments=dict(function_call.args)
        )
        print(f'------------reposne: {response}')
        return [parse_content(content) for content in response.content]

    return response.candidates[0].content.parts[0].text

